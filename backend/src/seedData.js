const DAY_MS = 24 * 60 * 60 * 1000;

function getRelativeIsoDate(offsetDays = 0) {
  const now = new Date();
  const target = new Date(Date.UTC(now.getFullYear(), now.getMonth(), now.getDate() + offsetDays));
  return target.toISOString().slice(0, 10);
}

function formatMonthDay(offsetDays = 0) {
  const now = new Date();
  const target = new Date(Date.UTC(now.getFullYear(), now.getMonth(), now.getDate() + offsetDays));
  return `${MONTHS_SHORT[target.getUTCMonth()]} ${String(target.getUTCDate()).padStart(2, '0')}`;
}

function formatRelativeDue(offsetDays = 0, time = '23:59') {
  return `${formatMonthDay(offsetDays)}, ${time}`;
}

function getWeekMondayIso(offsetWeeks = 0) {
  const now = new Date();
  const daysSinceMonday = (now.getDay() + 6) % 7;
  const mondayMs =
    Date.UTC(now.getFullYear(), now.getMonth(), now.getDate() - daysSinceMonday) +
    offsetWeeks * 7 * DAY_MS;
  return new Date(mondayMs).toISOString().slice(0, 10);
}

